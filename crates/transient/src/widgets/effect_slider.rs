//! `EffectSlider`: one effect's slider row in the Track tab.
//!
//! Every effect has the same kind of slider: a title with the current value
//! beside it ("Cut Below … 80 Hz"), the slider, and captions for its two ends.
//! This widget is that row, so window.blp only sets the texts and the range,
//! and the window reads and sets the slider through [`EffectSlider::scale`].
//!
//! It is an `AdwPreferencesRow`, so it sits in a preferences group like any
//! other row, and it uses the row's own `title`.

use adw::subclass::prelude::*;
use gtk::glib;

mod imp {
    // `#[derive(glib::Properties)]` generates `pub fn` getters and setters on
    // the `pub(crate)` wrapper type; that generated code is what this reports.
    #![expect(
        unreachable_pub,
        reason = "pub accessors generated by glib::Properties"
    )]

    use std::cell::{Cell, RefCell};

    use adw::prelude::*;
    use adw::subclass::prelude::*;
    use gtk::glib;

    /// The row's texts and range, as GObject properties so Blueprint can set
    /// them; the template binds its labels and slider to them.
    #[derive(Debug, gtk::CompositeTemplate, glib::Properties)]
    #[template(resource = "/io/github/sophiedkk/Transient/ui/effect-slider.ui")]
    #[properties(wrapper_type = super::EffectSlider)]
    pub(crate) struct EffectSlider {
        #[template_child]
        pub(super) scale: TemplateChild<gtk::Scale>,

        /// The current value, shown right of the title (for example "80 Hz").
        #[property(get, set)]
        value_text: RefCell<String>,
        /// What the left end of the slider means.
        #[property(get, set)]
        start_label: RefCell<String>,
        /// What the right end means.
        #[property(get, set)]
        end_label: RefCell<String>,
        /// The slider's range and steps.
        #[property(get, set, nullable)]
        adjustment: RefCell<Option<gtk::Adjustment>>,
        /// The decimals the slider rounds to while dragged; −1 is none.
        #[property(get, set, minimum = -1)]
        round_digits: Cell<i32>,
    }

    impl Default for EffectSlider {
        fn default() -> Self {
            Self {
                scale: TemplateChild::default(),
                value_text: RefCell::default(),
                start_label: RefCell::default(),
                end_label: RefCell::default(),
                adjustment: RefCell::default(),
                // GTK's own default: no rounding.
                round_digits: Cell::new(-1),
            }
        }
    }

    #[glib::object_subclass]
    impl ObjectSubclass for EffectSlider {
        const NAME: &'static str = "TransientEffectSlider";
        type Type = super::EffectSlider;
        type ParentType = adw::PreferencesRow;

        fn class_init(klass: &mut Self::Class) {
            klass.bind_template();
        }

        fn instance_init(obj: &glib::subclass::InitializingObject<Self>) {
            obj.init_template();
        }
    }

    #[glib::derived_properties]
    impl ObjectImpl for EffectSlider {
        fn constructed(&self) {
            self.parent_constructed();
            // A screen reader names the slider after the row's title.
            let row = self.obj();
            let scale = self.scale.get();
            let name_slider = move |row: &super::EffectSlider| {
                scale.update_property(&[gtk::accessible::Property::Label(&row.title())]);
            };
            name_slider(&row);
            row.connect_title_notify(name_slider);
        }
    }

    impl WidgetImpl for EffectSlider {}
    impl ListBoxRowImpl for EffectSlider {}
    impl PreferencesRowImpl for EffectSlider {}
}

glib::wrapper! {
    /// One effect's slider row: title, value, slider and end captions.
    pub(crate) struct EffectSlider(ObjectSubclass<imp::EffectSlider>)
        @extends adw::PreferencesRow, gtk::ListBoxRow, gtk::Widget,
        @implements gtk::Accessible, gtk::Actionable, gtk::Buildable, gtk::ConstraintTarget;
}

impl EffectSlider {
    /// The slider itself, to read its value and follow its changes.
    pub(crate) fn scale(&self) -> gtk::Scale {
        self.imp().scale.get()
    }
}
